#!/usr/bin/env python3
"""Writes core/Widths.java: the terminal width of every code point as glibc's wcwidth() says, which is what tmux
uses (and so what Force's screen is laid out by). Run on Linux after a glibc/Unicode update."""
import ctypes
import ctypes.util
from pathlib import Path

libc = ctypes.CDLL(ctypes.util.find_library("c"))
libc.setlocale(6, b"C.UTF-8")                    # LC_ALL
libc.wcwidth.restype = ctypes.c_int


def ranges(want):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            hit = libc.wcwidth(ctypes.c_wchar(chr(cp))) == want
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


zero = [r for r in ranges(0) if r[1] >= 0x80]    # combining marks, joiners (ASCII has none)
wide = ranges(2)
flat = lambda rs: ",\n            ".join(", ".join(f"0x{a:X}, 0x{b:X}" for a, b in rs[i:i + 6]) for i in range(0, len(rs), 6))
java = f"""package cc.useforce.mc.core;

/** Terminal widths as glibc's wcwidth() gives them (what tmux uses). Generated by scripts/widths.py: do not edit. */
final class Widths {{
    private Widths() {{}}

    /** Zero-width code points (combining marks, joiners): pairs of first, last. */
    static final int[] ZERO = {{
            {flat(zero)}
    }};

    /** Double-width code points (East Asian wide, emoji): pairs of first, last. */
    static final int[] WIDE = {{
            {flat(wide)}
    }};

    static boolean in(int[] table, int cp) {{
        int lo = 0, hi = table.length / 2 - 1;
        while (lo <= hi) {{
            int mid = (lo + hi) >>> 1;
            if (cp < table[2 * mid]) hi = mid - 1;
            else if (cp > table[2 * mid + 1]) lo = mid + 1;
            else return true;
        }}
        return false;
    }}
}}
"""
out = Path(__file__).resolve().parent.parent / "src/main/java/cc/useforce/mc/core/Widths.java"
out.write_text(java)
print(f"{len(zero)} zero-width and {len(wide)} wide ranges -> {out}")
